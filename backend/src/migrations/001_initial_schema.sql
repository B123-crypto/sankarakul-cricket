CREATE TABLE IF NOT EXISTS admins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (btrim(name) <> ''),
    email TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'admin'
        CHECK (role IN ('admin', 'super_admin')),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS teams (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (btrim(name) <> ''),
    short_name TEXT NOT NULL CHECK (btrim(short_name) <> ''),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS teams_name_unique_idx
    ON teams (LOWER(name));

CREATE UNIQUE INDEX IF NOT EXISTS teams_short_name_unique_idx
    ON teams (LOWER(short_name));

CREATE TABLE IF NOT EXISTS players (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id BIGINT NOT NULL REFERENCES teams(id),
    name TEXT NOT NULL CHECK (btrim(name) <> ''),
    role TEXT NOT NULL
        CHECK (role IN ('batter', 'bowler', 'all_rounder', 'wicket_keeper')),
    jersey_number INTEGER CHECK (jersey_number IS NULL OR jersey_number > 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (team_id, name),
    UNIQUE (team_id, jersey_number)
);

CREATE TABLE IF NOT EXISTS matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    home_team_id BIGINT NOT NULL REFERENCES teams(id),
    away_team_id BIGINT NOT NULL REFERENCES teams(id),
    format TEXT NOT NULL CHECK (format IN ('T20', 'ODI', 'TEST')),
    status TEXT NOT NULL DEFAULT 'scheduled'
        CHECK (status IN ('scheduled', 'live', 'completed', 'abandoned')),
    venue TEXT,
    scheduled_at TIMESTAMPTZ,
    overs_per_innings INTEGER,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (home_team_id <> away_team_id),
    CHECK (
        (format = 'TEST' AND overs_per_innings IS NULL)
        OR
        (
            format IN ('T20', 'ODI')
            AND overs_per_innings IS NOT NULL
            AND overs_per_innings BETWEEN 1 AND 100
        )
    )
);

CREATE INDEX IF NOT EXISTS matches_status_scheduled_idx
    ON matches (status, scheduled_at);

CREATE TABLE IF NOT EXISTS innings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id BIGINT NOT NULL REFERENCES matches(id) ON DELETE CASCADE,
    innings_number SMALLINT NOT NULL CHECK (innings_number BETWEEN 1 AND 4),
    batting_team_id BIGINT NOT NULL REFERENCES teams(id),
    bowling_team_id BIGINT NOT NULL REFERENCES teams(id),
    status TEXT NOT NULL DEFAULT 'scheduled'
        CHECK (status IN ('scheduled', 'live', 'completed')),
    target_runs INTEGER CHECK (target_runs IS NULL OR target_runs > 0),
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (match_id, innings_number),
    CHECK (batting_team_id <> bowling_team_id)
);

CREATE INDEX IF NOT EXISTS innings_match_status_idx
    ON innings (match_id, status);

CREATE TABLE IF NOT EXISTS deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    innings_id BIGINT NOT NULL REFERENCES innings(id) ON DELETE CASCADE,
    delivery_number INTEGER NOT NULL CHECK (delivery_number > 0),
    striker_id BIGINT NOT NULL REFERENCES players(id),
    non_striker_id BIGINT NOT NULL REFERENCES players(id),
    bowler_id BIGINT NOT NULL REFERENCES players(id),
    batter_runs INTEGER NOT NULL DEFAULT 0 CHECK (batter_runs >= 0),
    extras_type TEXT
        CHECK (extras_type IS NULL OR extras_type IN ('wide', 'no_ball', 'bye', 'leg_bye', 'penalty')),
    extras_runs SMALLINT NOT NULL DEFAULT 0 CHECK (extras_runs BETWEEN 0 AND 100),
    legal_ball BOOLEAN NOT NULL DEFAULT TRUE,
    wicket_type TEXT
        CHECK (
            wicket_type IS NULL
            OR wicket_type IN (
                'bowled', 'caught', 'lbw', 'run_out', 'stumped',
                'hit_wicket', 'retired_out', 'obstructing_field',
                'hit_ball_twice', 'timed_out'
            )
        ),
    dismissed_player_id BIGINT REFERENCES players(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (innings_id, delivery_number),
    CHECK (striker_id <> non_striker_id),
    CONSTRAINT deliveries_legal_ball_consistency CHECK (
        (
            extras_type IS NOT NULL
            AND extras_type IN ('wide', 'no_ball')
            AND legal_ball = FALSE
        )
        OR
        (
            (extras_type IS NULL OR extras_type NOT IN ('wide', 'no_ball'))
            AND legal_ball = TRUE
        )
    ),
    CHECK (extras_type NOT IN ('wide', 'no_ball') OR extras_runs >= 1),
    CHECK (
        (wicket_type IS NULL AND dismissed_player_id IS NULL)
        OR
        (wicket_type IS NOT NULL AND dismissed_player_id IS NOT NULL)
    )
);

CREATE INDEX IF NOT EXISTS deliveries_innings_order_idx
    ON deliveries (innings_id, delivery_number);
